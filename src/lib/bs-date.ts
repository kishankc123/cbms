export type BsDate = { year: number; month: number; day: number };

/** Converts an AD (Gregorian) date to its BS (Bikram Sambat) equivalent. */
export function adToBs(adDate: Date): BsDate {
  const target = Date.UTC(adDate.getFullYear(), adDate.getMonth(), adDate.getDate());
  let remaining = Math.round((target - BS_EPOCH_AD) / 86_400_000);
  if (remaining < 0) {
    throw new Error("Date is before the supported BS calendar range (BS 2000-01-01)");
  }

  let year = BS_EPOCH_YEAR;
  let months = BS_CALENDAR_DATA[year - BS_EPOCH_YEAR];
  while (months) {
    const yearTotal = months.reduce((a, b) => a + b, 0);
    if (remaining < yearTotal) break;
    remaining -= yearTotal;
    year += 1;
    months = BS_CALENDAR_DATA[year - BS_EPOCH_YEAR];
  }
  if (!months) {
    throw new Error("Date is after the supported BS calendar range (BS 2099-12-30)");
  }

  let month = 0;
  while (remaining >= months[month]) {
    remaining -= months[month];
    month += 1;
  }

  return { year, month: month + 1, day: remaining + 1 };
}

export function formatBsDate(bs: BsDate): string {
  return `${BS_MONTH_NAMES[bs.month - 1]} ${bs.day}, ${bs.year}`;
}
